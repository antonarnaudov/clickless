// Generates src/renderer/common/brand-icons.ts from @lobehub/icons-static-svg (MIT, lobehub/lobe-icons):
// the logos shown next to AI providers and agent clients. Run after changing the list:
//   node scripts/brand-icons.mjs
// Logos are trademarks of their owners and are used only to identify the service you connect.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'node_modules/@lobehub/icons-static-svg/icons');
const ICONS = {
  anthropic: 'anthropic',
  claude: 'claude-color',
  'claude-code': 'claudecode-color',
  openai: 'openai',
  codex: 'codex-color',
  gemini: 'gemini-color',
  'gemini-cli': 'geminicli-color',
  openrouter: 'openrouter',
  ollama: 'ollama',
  lmstudio: 'lmstudio',
  groq: 'groq',
  cursor: 'cursor',
  copilot: 'githubcopilot',
  windsurf: 'windsurf',
  cline: 'cline',
  mcp: 'mcp',
  deepseek: 'deepseek-color',
  mistral: 'mistral-color',
};
const out = {};
for (const [key, file] of Object.entries(ICONS)) {
  let svg = fs.readFileSync(path.join(dir, `${file}.svg`), 'utf8');
  svg = svg
    .replace(/<title>.*?<\/title>/s, '')
    .replace(/\s(width|height)="1em"/g, '')
    .replace(/\sstyle="[^"]*"/, '')
    .replace(/<svg /, '<svg aria-hidden="true" focusable="false" ');
  if (/<script|on\w+=/i.test(svg)) throw new Error(`${file}: unexpected content`);
  out[key] = svg.trim();
}
const pkg = JSON.parse(fs.readFileSync(path.join(dir, '..', 'package.json'), 'utf8'));
const body = `// Generated by scripts/brand-icons.mjs from @lobehub/icons-static-svg ${pkg.version} (MIT, github.com/lobehub/lobe-icons).
// Logos are trademarks of their owners, shown only to identify the service you connect. Do not edit by hand.

export const BRAND_ICONS = ${JSON.stringify(out, null, 2)} as const;

export type BrandName = keyof typeof BRAND_ICONS;
`;
fs.writeFileSync(path.join(root, 'src/renderer/common/brand-icons.ts'), body);
console.log(`wrote ${Object.keys(out).length} icons`);
